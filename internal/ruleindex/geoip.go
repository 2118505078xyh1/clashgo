// GeoIPCidrs returns the built-in CIDR prefixes for a country code (case
// insensitive, e.g. "cn", "CN", "hk"). It returns nil for unknown codes.
// Parsed results are cached; the returned slice is a copy safe for the caller
// to modify.
func GeoIPCidrs(country string) []netip.Prefix {
	key := strings.ToLower(strings.TrimSpace(country))
	if v, ok := geoCache.Load(key); ok {
		return append([]netip.Prefix(nil), v.([]netip.Prefix)...)
	}
	raw, ok := geoCIDRs[key]
	if !ok {
		return nil
	}
	out := make([]netip.Prefix, 0, len(raw))
	for _, s := range raw {
		if p, err := netip.ParsePrefix(s); err == nil {
			out = append(out, p.Masked())
		}
	}
	geoCache.Store(key, out)
	return append([]netip.Prefix(nil), out...)
}
